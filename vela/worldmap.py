def project(lon: float, lat: float, width: float, height: float) -> tuple[float, float]:
    """Proyección equirectangular recortada a [LAT_BOTTOM, LAT_TOP]."""
    x = (lon + 180.0) / 360.0 * width
    y = (LAT_TOP - max(LAT_BOTTOM, min(LAT_TOP, lat))) / (LAT_TOP - LAT_BOTTOM) * height
    return x, y


def _inside(lon: float, lat: float, poly) -> bool:
    inside = False
    j = len(poly) - 1
    for i in range(len(poly)):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def is_land(lon: float, lat: float) -> bool:
    return any(_inside(lon, lat, p) for p in LAND.values())


_RASTER_CACHE: dict[tuple, list[list[bool]]] = {}


def osm_rings() -> list[list[tuple[float, float]]] | None:
    from . import osmmap
    bm = osmmap.load()
    return bm.world_rings(0) if bm else None


def raster_rings(rings, cols: int, rows: int) -> list[list[bool]]:
    """Rasterizado por barrido (par-impar): una pasada por fila sobre todas las aristas."""
    import bisect
    edges = []
    for r in rings:
        for (x1, y1), (x2, y2) in zip(r, r[1:] + r[:1]):
            if y1 != y2:
                edges.append((x1, y1, x2, y2))
    grid = []
    for row in range(rows):
        lat = LAT_TOP - (row + 0.5) / rows * (LAT_TOP - LAT_BOTTOM)
        xs = sorted(x1 + (lat - y1) * (x2 - x1) / (y2 - y1) for x1, y1, x2, y2 in edges
                    if (y1 <= lat) != (y2 <= lat))
        grid.append([bisect.bisect(xs, -180 + (c + 0.5) / cols * 360) % 2 == 1 for c in range(cols)])
    return grid


def raster(cols: int, rows: int) -> list[list[bool]]:
    rings = osm_rings()
    key = (cols, rows, rings is not None)
    if key not in _RASTER_CACHE and rings is not None:
        _RASTER_CACHE[key] = raster_rings(rings, cols, rows)
    if key not in _RASTER_CACHE:
        grid = []
        for r in range(rows):
            lat = LAT_TOP - (r + 0.5) / rows * (LAT_TOP - LAT_BOTTOM)
            grid.append([is_land(-180 + (c + 0.5) / cols * 360, lat) for c in range(cols)])
        _RASTER_CACHE[key] = grid
    return _RASTER_CACHE[key]


def ascii_map(cols: int, rows: int, markers: list[tuple[float, float, str]] = ()) -> list[str]:
    """Mapa en texto; `markers` = [(lat, lon, carácter)]."""
    grid = [["·" if land else " " for land in row] for row in raster(cols, rows)]
    for lat, lon, ch in markers:
        if lat is None or lon is None:
            continue
        x, y = project(lon, lat, cols, rows)
        c, r = min(cols - 1, max(0, int(x))), min(rows - 1, max(0, int(y)))
        grid[r][c] = ch
    return ["".join(row) for row in grid]


def as_json() -> dict:
    rings = osm_rings()
    if rings is not None:
        from .osmmap import ATTRIBUTION
        return {"lat_top": LAT_TOP, "lat_bottom": LAT_BOTTOM, "land": {}, "attribution": ATTRIBUTION,
                "rings": [[[round(x, 2), round(y, 2)] for x, y in r] for r in rings]}
    return {"lat_top": LAT_TOP, "lat_bottom": LAT_BOTTOM,
            "land": {k: [[x, y] for x, y in v] for k, v in LAND.items()}}
